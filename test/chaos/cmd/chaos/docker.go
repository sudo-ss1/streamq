// imageOverride retags the broker image so the chaos project never re-tags the dev cluster's
// streamq:dev image (plan M9 R29). It is written into the results directory at start-up and
// passed to every compose command after the base file.
const imageOverride = `# Generated by test/chaos/cmd/chaos: tag the chaos broker image separately (plan M9 R29).
services:
  broker1:
    image: streamq:chaos
  broker2:
    image: streamq:chaos
  broker3:
    image: streamq:chaos
`

// busyboxImage is the helper image for the full-disk scenario (fill and cleanup of broker3's log
// volume, and the one-shot chown of its Raft volume in deploy/docker-compose.chaos.yml).
const busyboxImage = "busybox:1.36"

// hostPorts are the host ports the chaos project publishes; they must be free (plan M9 R25).
func hostPorts() []int { return []int{9092, 9192, 9292, 8474} }

// compose runs docker compose commands against the chaos project. Every container action goes
// through it (kill, pause, unpause, start), so no container outside the project is touched
// (plan M9 R29).
type compose struct {
	project  string
	base     []string // compose file + image override
	override string   // full-disk override, used only by the full-disk scenario
}

// files returns the compose files for a scenario.
func (c *compose) files(fullDisk bool) []string {
	fs := append([]string(nil), c.base...)
	if fullDisk {
		fs = append(fs, c.override)
	}
	return fs
}

// run executes `docker compose -p <project> -f ... args...` and returns its combined output.
func (c *compose) run(ctx context.Context, fullDisk bool, args ...string) (string, error) {
	full := []string{"compose", "-p", c.project}
	for _, f := range c.files(fullDisk) {
		full = append(full, "-f", f)
	}
	full = append(full, args...)
	return docker(ctx, full...)
}

// docker runs the docker CLI and returns its combined output.
func docker(ctx context.Context, args ...string) (string, error) {
	cmd := exec.CommandContext(ctx, "docker", args...)
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &out
	err := cmd.Run()
	if err != nil {
		return out.String(), fmt.Errorf("docker %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(lastLines(out.String(), 20)))
	}
	return out.String(), nil
}

// lastLines returns the last n lines of s.
func lastLines(s string, n int) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, "\n")
}

// volumeName is the docker name of a compose project's named volume.
func (c *compose) volumeName(v string) string { return c.project + "_" + v }

// down removes the project's containers and every volume it owns. `down -v` only removes the
// volumes the given files' services use (with the full-disk override, broker3-data is unused
// and would survive, carrying a previous scenario's logs and Raft state into the next), so it
// runs with both file sets and then removes any volume still labelled with the project.
func (c *compose) down(ctx context.Context) error {
	var errs []error
	for _, fullDisk := range []bool{true, false} {
		if _, err := c.run(ctx, fullDisk, "down", "-v", "--remove-orphans", "-t", "5"); err != nil {
			errs = append(errs, err)
		}
	}
	out, err := docker(ctx, "volume", "ls", "-q", "--filter", "label=com.docker.compose.project="+c.project)
	if err != nil {
		return errors.Join(append(errs, err)...)
	}
	for _, v := range strings.Fields(out) {
		if _, err := docker(ctx, "volume", "rm", "-f", v); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// up starts toxiproxy and the three brokers (no Prometheus or Grafana, plan M9 R14). With the
// full-disk override, broker3's dependency (the one-shot Raft volume chown) starts too.
func (c *compose) up(ctx context.Context, fullDisk bool) error {
	_, err := c.run(ctx, fullDisk, "up", "-d", "--no-build", "toxiproxy", "broker1", "broker2", "broker3")
	return err
}

// service returns the compose service name of a broker.
func service(broker int32) string { return fmt.Sprintf("broker%d", broker) }

// kill9 sends SIGKILL to a broker's container.
func (c *compose) kill9(ctx context.Context, fullDisk bool, broker int32) error {
	_, err := c.run(ctx, fullDisk, "kill", "-s", "SIGKILL", service(broker))
	return err
}

// start starts a stopped broker container.
func (c *compose) start(ctx context.Context, fullDisk bool, broker int32) error {
	_, err := c.run(ctx, fullDisk, "start", service(broker))
	return err
}

// pause freezes a broker container (cgroup freezer; its sockets stay open).
func (c *compose) pause(ctx context.Context, broker int32) error {
	_, err := c.run(ctx, false, "pause", service(broker))
	return err
}

// unpause thaws a paused broker container.
func (c *compose) unpause(ctx context.Context, broker int32) error {
	_, err := c.run(ctx, false, "unpause", service(broker))
	return err
}

// containerState returns the docker state ("running", "exited", ...) of a broker's container,
// looked up by the ID from `docker compose ps -q`.
func (c *compose) containerState(ctx context.Context, fullDisk bool, broker int32) (string, error) {
	out, err := c.run(ctx, fullDisk, "ps", "-a", "-q", service(broker))
	if err != nil {
		return "", err
	}
	id := strings.TrimSpace(out)
	if id == "" {
		return "absent", nil
	}
	state, err := docker(ctx, "inspect", "-f", "{{.State.Status}} exit={{.State.ExitCode}} oom={{.State.OOMKilled}}", id)
	return strings.TrimSpace(state), err
}

// saveLogs writes every service's logs of the project to path.
func (c *compose) saveLogs(ctx context.Context, fullDisk bool, path string) error {
	out, err := c.run(ctx, fullDisk, "logs", "--no-color", "--timestamps")
	if werr := os.WriteFile(path, []byte(out), 0o600); werr != nil {
		return errors.Join(err, werr)
	}
	return err
}

// imageID returns the ID of a local image.
func imageID(ctx context.Context, image string) (string, error) {
	out, err := docker(ctx, "image", "inspect", "-f", "{{.Id}}", image)
	return strings.TrimSpace(out), err
}

// checkPortsFree fails if any chaos host port is already bound (plan M9 R25).
func checkPortsFree(ctx context.Context) error {
	var busy []string
	for _, p := range hostPorts() {
		lis, err := (&net.ListenConfig{}).Listen(ctx, "tcp", fmt.Sprintf(":%d", p))
		if err != nil {
			busy = append(busy, fmt.Sprint(p))
			continue
		}
		_ = lis.Close()
	}
	if len(busy) > 0 {
		return fmt.Errorf("host port(s) %s already in use: stop the dev cluster (make cluster-down) or whatever holds them", strings.Join(busy, ", "))
	}
	return nil
}

// gitSHA returns HEAD's SHA, suffixed with -dirty when the worktree has changes.
func gitSHA(ctx context.Context) string {
	out, err := exec.CommandContext(ctx, "git", "rev-parse", "HEAD").Output()
	if err != nil {
		return "unknown"
	}
	sha := strings.TrimSpace(string(out))
	status, err := exec.CommandContext(ctx, "git", "status", "--porcelain", "--untracked-files=no").Output()
	if err == nil && len(bytes.TrimSpace(status)) > 0 {
		sha += "-dirty"
	}
	return sha
}

// ctl runs the streamqctl binary.
type ctl struct{ path string }

// clusterStatusStrict runs `streamqctl cluster status --strict` against addr.
func (c ctl) clusterStatusStrict(ctx context.Context, addr string) (string, error) {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, c.path, "--bootstrap", addr, "--timeout", "3s", "cluster", "status", "--strict")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// writeImageOverride writes the image override into dir and returns its absolute path.
func writeImageOverride(dir string) (string, error) {
	path, err := filepath.Abs(filepath.Join(dir, "docker-compose.image.yml"))
	if err != nil {
		return "", err
	}
	return path, os.WriteFile(path, []byte(imageOverride), 0o600)
}
